"""Per-project run history — collects a snapshot of numbers from every `lab run`
("predicted") and lets a human add a real observation once something is actually built or
tested ("measured": a weighed mass, a timed run, a measured speed), then compares the two.

Domain-agnostic on purpose, like the rest of `core`: it only ever touches the handful of
whole-project numbers every domain's `results` already share (`total_mass_kg`,
`total_cost_rub`) plus whatever flat, numeric calculation metrics a domain happened to
produce — it never refers to a hull or a wing by name. A boat project's
`hydrostatics.waterline_transom_mm` and an aircraft project's `wing_loading.wing_loading_g_dm2`
both just show up as metric keys; this module doesn't know or care which domain made them.

Unlike `export/` (regenerated every run, gitignored — see Lab/.gitignore), `history.jsonl`
lives at the project's own top level and is **not** gitignored: a "measured" record is a real
observation that cannot be regenerated by rerunning `lab run`, so it has to be committed like
any other real data (the same reasoning boat-rc's own hand-written comparison tables and
float-test write-ups follow, just structured instead of free-form markdown).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

HISTORY_FILE = "history.jsonl"


@dataclass
class StatsRecord:
    timestamp: str
    kind: str  # "predicted" | "measured"
    metrics: dict[str, float]
    note: str = ""


@dataclass
class MetricSummary:
    predicted_count: int
    measured_count: int
    latest_predicted: float | None
    latest_measured: float | None
    diff_pct: float | None  # (measured - predicted) / predicted * 100, when both exist


def _history_path(project_dir: Path) -> Path:
    return project_dir / HISTORY_FILE


def _flatten_calculations(calculations: dict[str, Any]) -> dict[str, float]:
    """`calc_name.key -> value`, numeric entries only — a calculator's `method`/`error`
    strings have nothing to trend over time, so they're left out rather than stored as
    unusable history.
    """

    flat: dict[str, float] = {}
    for calc_name, metrics in calculations.items():
        if not isinstance(metrics, dict):
            continue
        for key, value in metrics.items():
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                flat[f"{calc_name}.{key}"] = value

    return flat


def _append(project_dir: Path, record: StatsRecord) -> None:
    line = json.dumps(
        {"timestamp": record.timestamp, "kind": record.kind, "metrics": record.metrics, "note": record.note},
        ensure_ascii=False,
    )
    with _history_path(project_dir).open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def record_predicted(project_dir: Path, results: dict[str, Any]) -> StatsRecord:
    """Called by `core/cli.py` after every `lab run` — never overwrites a previous run's
    record, so a project's history is every run that was ever made, not just the last one.
    """

    metrics = {
        "total_mass_kg": results["total_mass_kg"],
        "total_cost_rub": results["total_cost_rub"],
        "build_mass_kg": results["build_mass_kg"],
        "build_cost_rub": results["build_cost_rub"],
        **_flatten_calculations(results.get("calculations", {})),
    }
    record = StatsRecord(timestamp=datetime.now(timezone.utc).isoformat(), kind="predicted", metrics=metrics)
    _append(project_dir, record)

    return record


def record_measured(project_dir: Path, metrics: dict[str, float], note: str = "") -> StatsRecord:
    """`lab measure <project_dir> key=value [key=value ...] [--note TEXT]` — a human-entered
    real observation, same metric-key namespace as `record_predicted` (e.g.
    `total_mass_kg=0.82` after weighing a printed hull) so it lines up with the predicted
    series for that key in `summarize()`.
    """

    record = StatsRecord(timestamp=datetime.now(timezone.utc).isoformat(), kind="measured", metrics=metrics, note=note)
    _append(project_dir, record)

    return record


def load_history(project_dir: Path) -> list[StatsRecord]:
    path = _history_path(project_dir)
    if not path.exists():
        return []

    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        raw = json.loads(line)
        records.append(StatsRecord(timestamp=raw["timestamp"], kind=raw["kind"], metrics=raw["metrics"], note=raw.get("note", "")))

    return records


def summarize(project_dir: Path) -> dict[str, MetricSummary]:
    """One `MetricSummary` per metric key ever recorded — latest predicted vs. latest
    measured and their difference, the comparison boat-rc's own `COMPARISON.md` makes by hand
    per revision, built once here from whatever history exists instead.
    """

    series: dict[str, dict[str, list[tuple[str, float]]]] = {}

    for record in load_history(project_dir):
        for key, value in record.metrics.items():
            series.setdefault(key, {"predicted": [], "measured": []})[record.kind].append((record.timestamp, value))

    summary: dict[str, MetricSummary] = {}
    for key, kinds in series.items():
        latest_predicted = kinds["predicted"][-1][1] if kinds["predicted"] else None
        latest_measured = kinds["measured"][-1][1] if kinds["measured"] else None
        diff_pct = (
            round((latest_measured - latest_predicted) / latest_predicted * 100, 1)
            if latest_predicted is not None and latest_measured is not None and latest_predicted != 0
            else None
        )
        summary[key] = MetricSummary(
            predicted_count=len(kinds["predicted"]),
            measured_count=len(kinds["measured"]),
            latest_predicted=latest_predicted,
            latest_measured=latest_measured,
            diff_pct=diff_pct,
        )

    return summary
